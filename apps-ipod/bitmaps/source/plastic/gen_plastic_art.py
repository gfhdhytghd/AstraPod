#!/usr/bin/env python3
"""Write apps-ipod/ui/plastic_art.c and plastic_columns.h from the PNGs here.

The PNGs are Apple's interface art, cut from the stock iPod Classic firmware's
screens; battery_empty.png is the full battery with its fill greyed. Run from
anywhere after changing one:

    python3 apps-ipod/bitmaps/source/plastic/gen_plastic_art.py
"""
from pathlib import Path

from PIL import Image

HERE = Path(__file__).resolve().parent
UI = HERE.parents[2] / 'ui'

# role, file, kind, x, y. "mask" art keeps only its alpha and is drawn in the
# foreground colour; x and y place it from where its caller anchors it: the
# battery's corner for the bolt, a speaker's left edge and centre line.
ART = [
    ('UI_ART_CHEVRON', 'chevron', 'mask', 0, 0),
    ('UI_ART_PLAY', 'play', 'image', 0, 0),
    ('UI_ART_PAUSE', 'pause', 'image', 0, 0),
    ('UI_ART_BATTERY_FULL', 'battery_full', 'image', 0, 0),
    ('UI_ART_BATTERY_EMPTY', 'battery_empty', 'image', 0, 0),
    ('UI_ART_CHARGING', 'charging', 'image', 9, 5),
    ('UI_ART_SHUFFLE', 'shuffle', 'image', 0, 0),
    ('UI_ART_SPEAKER_QUIET', 'speaker_quiet', 'image', 0, -6),
    ('UI_ART_SPEAKER_LOUD', 'speaker_loud', 'image', 0, -8),
]

COLUMNS = ['status', 'selection', 'progress', 'progress_track']

HEADER = ('/* Generated by apps-ipod/bitmaps/source/plastic/gen_plastic_art.py '
          'from\n * Apple\'s art beside it. Do not edit. */\n')


def rows(items, per_line, indent='    '):
    out = []
    for i in range(0, len(items), per_line):
        out.append(indent + ', '.join(items[i:i + per_line]) + ',')
    return '\n'.join(out)


def nibbles(alpha):
    """0 opaque to 15 clear, first pixel in the low nibble."""
    clear = [15 - (a * 15 + 127) // 255 for a in alpha]
    if len(clear) % 2:
        clear.append(15)
    return ['0x%02x' % (clear[i] | clear[i + 1] << 4)
            for i in range(0, len(clear), 2)]


def art_source():
    body = [HEADER, '#include "theme_art.h"\n']
    table = []
    for role, name, kind, dx, dy in ART:
        im = Image.open(HERE / (name + '.png')).convert('RGBA')
        px = [im.getpixel((x, y)) for y in range(im.height)
              for x in range(im.width)]
        alpha = [p[3] for p in px]
        pixels = alpha_name = 'NULL'
        if kind == 'image':
            pixels = name + '_pixels'
            body.append('static const fb_data %s[] = {\n%s\n};\n' % (
                pixels, rows(['FB_RGBPACK(%d, %d, %d)' % p[:3] for p in px], 2)))
        if kind == 'mask' or min(alpha) < 255:
            alpha_name = name + '_alpha'
            body.append('static const unsigned char %s[] = {\n%s\n};\n' % (
                alpha_name, rows(nibbles(alpha), 12)))
        table.append('    [%s] = { %d, %d, %d, %d,\n        %s, %s },' % (
            role, im.width, im.height, dx, dy, pixels, alpha_name))
    body.append('const struct ui_art plastic_art[UI_ART_COUNT] = {\n%s\n};\n'
                % '\n'.join(table))
    return '\n'.join(body)


def columns_source():
    body = [HEADER, '#ifndef PLASTIC_COLUMNS_H\n#define PLASTIC_COLUMNS_H\n',
            '/* RGB888, top to bottom. */']
    for name in COLUMNS:
        im = Image.open(HERE / (name + '.png')).convert('RGB')
        values = ['0x%02x%02x%02x' % im.getpixel((0, y))
                  for y in range(im.height)]
        body.append('static const uint32_t plastic_%s[] = {\n%s\n};' % (
            name, rows(values, 6)))
    body.append('\n#endif')
    return '\n'.join(body) + '\n'


(UI / 'plastic_art.c').write_text(art_source())
(UI / 'plastic_columns.h').write_text(columns_source())
