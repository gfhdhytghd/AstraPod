#!/usr/bin/env python3
"""Generate the fixed comparison glyph samples for PodBox's ClearType test."""
import argparse
from pathlib import Path
import tempfile

from compile import ALPHA, Face, build_raster, cjk, fontconfig
from fusion import FUSION_CACHE, FUSION_SHA256, FUSION_VERSION, glyph_bitmap, load_fusion

SIZES = (8, 10, *range(12, 19))
SAMPLES = ("Il1 48", "正在播放")
MODES = ("pixel", "rgb", "aligned")
def pixel_glyphs(chars, fusion):
    pen = 0
    glyphs = []
    for cp in chars:
        g = fusion[cp]
        if g.w and g.h:
            (left, top, width, height), ink = glyph_bitmap(g)
            glyphs.append((pen + left, -top, width, height, ink))
        pen += g.adv
    return glyphs


def rasterize(face, text, fusion):
    chars = tuple(map(ord, text))
    pens = face.layout(chars)
    if pens is None or any(cp not in face.cmap for cp in chars):
        raise ValueError(f"Cannot lay out {text!r} with {face.name}")
    variants = [pixel_glyphs(chars, fusion) if fusion else []]
    for aligned in (False, True):
        glyphs = []
        for cp, pen in zip(chars, pens):
            snap = aligned or cjk(cp)
            rounded = pen + (32 if snap else 8)
            phase = 0 if snap else rounded & 48
            (left, top, width, height), pixels = face.bitmap(
                cp, phase, lcd=True, aligned=aligned)
            if width and height:
                glyphs.append(((rounded >> 6) + left, -top, width, height, pixels))
        variants.append(glyphs)

    bounds = [glyph for glyphs in variants for glyph in glyphs]
    left = min(g[0] for g in bounds)
    top = min(g[1] for g in bounds)
    width = max(g[0] + g[2] for g in bounds) - left
    height = max(g[1] + g[3] for g in bounds) - top
    if width > 74 or height > 21:
        raise ValueError(f"{text!r} does not fit the test page")

    masks = []
    for channels, glyphs in zip((1, 3, 3), variants):
        if not glyphs:
            masks.append(None)
            continue
        mask = [0] * (width * height * 3)
        for x, y, w, h, pixels in glyphs:
            for row in range(h):
                for col in range(w):
                    src = (row * w + col) * channels
                    dst = ((y - top + row) * width + x - left + col) * 3
                    for channel in range(3):
                        coverage = pixels[src + (channel if channels == 3 else 0)]
                        alpha = 15 - ALPHA[coverage]
                        old = mask[dst + channel]
                        mask[dst + channel] = old + ((15 - old) * alpha + 7) // 15
        masks.append([(r << 8) | (g << 4) | b for r, g, b in
                      zip(mask[0::3], mask[1::3], mask[2::3])])

    if any(not any((v >> 8) != (v & 15) for v in mask) for mask in masks[1:]):
        raise ValueError(f"LCD rasterizer produced no colored samples for {text!r}")
    if masks[1] == masks[2]:
        raise ValueError(f"Aligned and unaligned samples match for {text!r}")
    return width, height, masks


def generate(lib, cache, scratch):
    catalog = fontconfig()
    faces = [Face(name, *min(catalog[name]), lib)
             for name in ("HarmonyOS Sans", "HarmonyOS Sans SC")]
    print("/* Generated by tools/fonts/lcd_test.py. RGB coverage, four bits per channel.")
    print(f" * Bitmap samples: Fusion Pixel Font {FUSION_VERSION}, under OFL 1.1.")
    print(" * See apps-ipod/fonts/LICENSE-Fusion-Pixel.txt. */")
    rows = []
    sizes = ", ".join(map(str, SIZES))
    print(f"static const unsigned char font_test_sizes[] = {{ {sizes} }};")
    try:
        for size in SIZES:
            fusion = load_fusion(size, cache, scratch) if size in FUSION_SHA256 else None
            for language, (face, sample) in enumerate(zip(faces, SAMPLES)):
                face.set_size(size, 400)
                width, height, masks = rasterize(face, sample, fusion)
                name = f"sample_{size}_{language}"
                for mode, mask in zip(MODES, masks):
                    if mask is None:
                        continue
                    print(f"/* {sample} */\nstatic const uint16_t {name}_{mode}[] = {{")
                    for start in range(0, len(mask), 12):
                        print("    " + ", ".join(f"0x{v:03x}" for v in mask[start:start + 12]) + ",")
                    print("};")
                arrays = ", ".join(f"{name}_{mode}" if mask is not None else "NULL"
                                   for mode, mask in zip(MODES, masks))
                rows.append(f"    {{ {width}, {height}, {{ {arrays} }} }},")
    finally:
        for face in faces:
            face.close()
    print("static const struct font_test_sample font_test_samples[] = {")
    print("\n".join(rows))
    print("};")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--fusion-cache", type=Path, default=FUSION_CACHE)
    args = parser.parse_args()
    with tempfile.TemporaryDirectory() as directory:
        scratch = Path(directory)
        generate(build_raster(scratch), args.fusion_cache, scratch)
