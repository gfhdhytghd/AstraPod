#!/usr/bin/env python3
"""Write the stock art's tables, or pack its pixels, from the PNGs here.

Most PNGs are bitmaps from the iPod Classic 1.1.2 resource bank, named
after their resource. SearchResult_* are icon tiles converted from the
2.0.5 LCD output. AstraPod_* are ours, drawn in the same style.
A greyscale PNG is a mask: its levels are
the alpha of a colour the caller picks. Any other PNG is an image with its
own alpha, kept as a palette and indices. A mask keeps only the rectangle
that holds its ink: the table records where it lies, and outside it the mask
reads as clear, so a hand frame costs its hand and not its whole dial.

    gen_stock_art.py              write apps-ipod/ui/stock_art_ids.h and
                                  stock_art_table.c; run after adding,
                                  removing or resizing a PNG
    gen_stock_art.py --pack FILE  write the pixels the firmware loads at
                                  run time; bundle-theme.sh does this

Pure Python, so a build host needs nothing beyond python3.
"""
import struct
import sys
import zlib
from pathlib import Path

HERE = Path(__file__).resolve().parent
UI = HERE.parents[2] / 'ui'
MAGIC = b'SART'
VERSION = 1

HEADER = ('/* Generated by apps-ipod/bitmaps/source/stock/gen_stock_art.py '
          'from\n * the bitmaps beside it. Do not edit. */\n')


def read_png(path):
    """(width, height, grey, pixels): grey bytes, or RGBA tuples."""
    data = path.read_bytes()
    if data[:8] != b'\x89PNG\r\n\x1a\n':
        raise ValueError('%s: not a PNG' % path)
    at, idat, palette, trns = 8, b'', b'', b''
    while at < len(data):
        size, kind = struct.unpack_from('>I4s', data, at)
        body = data[at + 8:at + 8 + size]
        if kind == b'IHDR':
            width, height, depth, color, _, _, interlace = struct.unpack(
                '>IIBBBBB', body)
        elif kind == b'IDAT':
            idat += body
        elif kind == b'PLTE':
            palette = body
        elif kind == b'tRNS':
            trns = body
        at += size + 12
    channels = {0: 1, 2: 3, 3: 1, 4: 2, 6: 4}[color]
    if depth != 8 or interlace:
        raise ValueError('%s: needs 8-bit channels, not interlaced' % path)
    raw = zlib.decompress(idat)
    stride = width * channels
    prev = bytearray(stride)
    rows = []
    for y in range(height):
        f = raw[y * (stride + 1)]
        row = bytearray(raw[y * (stride + 1) + 1:(y + 1) * (stride + 1)])
        for x in range(stride):
            a = row[x - channels] if x >= channels else 0
            b = prev[x]
            c = prev[x - channels] if x >= channels else 0
            if f == 1:
                row[x] = (row[x] + a) & 255
            elif f == 2:
                row[x] = (row[x] + b) & 255
            elif f == 3:
                row[x] = (row[x] + (a + b) // 2) & 255
            elif f == 4:
                p = a + b - c
                pa, pb, pc = abs(p - a), abs(p - b), abs(p - c)
                row[x] = (row[x] + (a if pa <= pb and pa <= pc else
                                    b if pb <= pc else c)) & 255
        rows.append(row)
        prev = row
    flat = b''.join(rows)
    if color == 0:
        return width, height, True, flat
    px = []
    for i in range(width * height):
        p = flat[i * channels:(i + 1) * channels]
        if color == 2:
            px.append((p[0], p[1], p[2], 255))
        elif color == 3:
            n = p[0]
            px.append(tuple(palette[n * 3:n * 3 + 3]) +
                      (trns[n] if n < len(trns) else 255,))
        elif color == 4:
            px.append((p[0], p[0], p[0], p[1]))
        else:
            px.append(tuple(p))
    return width, height, False, px


def ident(path):
    name = path.stem
    if name.endswith('_Image'):
        name = name[:-len('_Image')]
    return 'STOCK_ART_' + name.upper()


def ink(width, height, px):
    """(x, y, width, height) of the smallest rectangle holding every
    non-zero pixel of a mask; one clear pixel when there is none."""
    rows = [y for y in range(height) if any(px[y * width:(y + 1) * width])]
    cols = [x for x in range(width)
            if any(px[y * width + x] for y in rows)]
    if not rows:
        return 0, 0, 1, 1
    return cols[0], rows[0], cols[-1] + 1 - cols[0], rows[-1] + 1 - rows[0]


def art():
    out = []
    for f in sorted(HERE.glob('*.png')):
        width, height, grey, px = read_png(f)
        if grey:
            x, y, w, h = ink(width, height, px)
            pixels = b''.join(px[(y + r) * width + x:(y + r) * width + x + w]
                              for r in range(h))
            out.append((ident(f), width, height, 0, b'', pixels,
                        x, y, w, h))
            continue
        palette = list(dict.fromkeys(px))
        index = {c: n for n, c in enumerate(palette)}
        code = '<B' if len(palette) <= 256 else '<H'
        pixels = b''.join(struct.pack(code, index[c]) for c in px)
        pal = b''.join(struct.pack('<I', a << 24 | r << 16 | g << 8 | b)
                       for r, g, b, a in palette)
        out.append((ident(f), width, height, len(palette), pal, pixels,
                    0, 0, width, height))
    return out


def fingerprint(items):
    """Ties a pack to the firmware built from the same PNGs."""
    key = ';'.join('%s %d %d %d' % i[:4] + ' %d %d %d %d' % i[6:]
                   for i in items).encode()
    return zlib.crc32(key)


def tables(items):
    ids = [HEADER, '#ifndef STOCK_ART_IDS_H\n#define STOCK_ART_IDS_H\n',
           '#define STOCK_ART_FINGERPRINT 0x%08xu\n' % fingerprint(items),
           'enum stock_art_id {']
    ids += ['    %s,' % i[0] for i in items]
    ids += ['    STOCK_ART_COUNT\n};\n', '#endif']
    (UI / 'stock_art_ids.h').write_text('\n'.join(ids) + '\n')
    table = [HEADER, '#include "stock_art.h"\n',
             '/* The pixels arrive from the pack, see stock_art.c. */',
             'struct stock_art stock_art[STOCK_ART_COUNT] = {']
    table += ['    [%s] = { %d, %d, %d, NULL, NULL, %d, %d, %d, %d },'
              % (i[:4] + i[6:]) for i in items]
    table += ['};']
    (UI / 'stock_art_table.c').write_text('\n'.join(table) + '\n')


def pack(items, path):
    """Header, then per art its palette and pixel offsets, then the data,
    every block 4-byte aligned. Little-endian throughout."""
    head = struct.pack('<4sIII', MAGIC, VERSION, len(items),
                       fingerprint(items))
    at = len(head) + 8 * len(items)
    blocks, offsets = [], []
    for _, _, _, _, pal, pixels, *_ in items:
        entry = []
        for block in (pal, pixels):
            entry.append(at if block else 0)
            blocks.append(block + bytes(-len(block) % 4))
            at += len(blocks[-1])
        offsets.append(struct.pack('<II', *entry))
    Path(path).write_bytes(head + b''.join(offsets) + b''.join(blocks))


def main():
    items = art()
    if len(sys.argv) == 3 and sys.argv[1] == '--pack':
        pack(items, sys.argv[2])
    elif len(sys.argv) == 1:
        tables(items)
    else:
        sys.exit(__doc__)


if __name__ == '__main__':
    main()
