#!/usr/bin/env python3
"""Write apps-ipod/ui/plastic_columns.h from selection.png beside it.

Stock's selection bar is a colour gradient rather than a bitmap, so it is
kept as the columns of its bars cut from the stock firmware's screen, one for
each height stock draws: 25 and 24 rows (selection.png, selection_24.png) and
the two-line 44 (selection_44.png). The rest of Plastic's art is the stock
bitmaps in ../stock/. Run from anywhere
after changing the PNG:

    python3 apps-ipod/bitmaps/source/plastic/gen_plastic_art.py
"""
from pathlib import Path

from PIL import Image

HERE = Path(__file__).resolve().parent
UI = HERE.parents[2] / 'ui'

COLUMNS = ['selection', 'selection_24', 'selection_44']

HEADER = ('/* Generated by apps-ipod/bitmaps/source/plastic/gen_plastic_art.py '
          'from\n * Apple\'s art beside it. Do not edit. */\n')


def rows(items, per_line, indent='    '):
    out = []
    for i in range(0, len(items), per_line):
        out.append(indent + ', '.join(items[i:i + per_line]) + ',')
    return '\n'.join(out)


def columns_source():
    body = [HEADER, '#ifndef PLASTIC_COLUMNS_H\n#define PLASTIC_COLUMNS_H\n',
            '/* RGB888, top to bottom. */']
    for name in COLUMNS:
        im = Image.open(HERE / (name + '.png')).convert('RGB')
        values = ['0x%02x%02x%02x' % im.getpixel((0, y))
                  for y in range(im.height)]
        body.append('static const uint32_t plastic_%s[] = {\n%s\n};' % (
            name, rows(values, 6)))
    body.append('\n#endif')
    return '\n'.join(body) + '\n'


(UI / 'plastic_columns.h').write_text(columns_source())
