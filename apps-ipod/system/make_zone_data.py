"""Generate zone_data.inc from a system IANA TZif directory (zic output)."""
import argparse
import datetime as dt
from pathlib import Path
import struct
from zoneinfo import ZoneInfo

START = 915148800  # 1999-01-01, includes the first local day of 2000
END = 2145916800  # 2038-01-01


def transitions(path):
    data = path.read_bytes()
    if not data.startswith((b"TZif2", b"TZif3", b"TZif4")):
        return None
    utc, std, leap, count, types, chars = struct.unpack_from(">6I", data, 20)
    header = 44 + utc + std + 8 * leap + 5 * count + 6 * types + chars
    count = struct.unpack_from(">I", data, header + 32)[0]
    times = struct.unpack_from(f">{count}q", data, header + 44)
    with path.open("rb") as source:
        zone = ZoneInfo.from_file(source)

    def state(timestamp):
        local = dt.datetime.fromtimestamp(timestamp, dt.timezone.utc).astimezone(zone)
        return int(local.utcoffset().total_seconds()), int(bool(local.dst()))

    result = [(START, *state(START))]
    for instant in times:
        if START < instant < END and state(instant) != result[-1][1:]:
            result.append((instant, *state(instant)))
    # Slim TZif files can defer future changes to their POSIX footer.
    stamp = min(END, max(START, max(times, default=START)))
    while stamp < END:
        stop = min(stamp + 86400, END)
        if state(stop) != result[-1][1:]:
            lo, hi = stamp, stop
            while hi - lo > 1:
                mid = (lo + hi) // 2
                if state(mid) == result[-1][1:]:
                    lo = mid
                else:
                    hi = mid
            if hi < END:
                result.append((hi, *state(hi)))
        stamp = stop
    footer = data.rsplit(b"\n", 2)[-2].decode("ascii") if data.endswith(b"\n") else ""
    return tuple(result), footer


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("zoneinfo", type=Path)
    args = parser.parse_args()
    root = args.zoneinfo
    version = (root / "tzdata.zi").read_text().splitlines()[0]
    canonical = {line.split()[2] for line in (root / "zone1970.tab").read_text().splitlines()
                 if line and not line.startswith("#")}
    pools, zones = {}, []
    cached = {}
    for path in sorted(root.rglob("*")):
        name = path.relative_to(root).as_posix()
        if not path.is_file() or name.split("/")[0] in ("posix", "right", "localtime",
                                                        "posixrules", "Factory"):
            continue
        resolved = path.resolve()
        if resolved not in cached:
            cached[resolved] = transitions(path)
        result = cached[resolved]
        if result:
            series, footer = result
            index = pools.setdefault(series, len(pools))
            zones.append((name, index, footer, name in canonical or name == "Etc/UTC"))
    print(f"/* Generated by make_zone_data.py from IANA tzdata ({version}). */")
    for series, i in pools.items():
        print(f"static const struct zone_change zone_{i}[] = {{")
        for timestamp, offset, dst in series:
            print(f"    {{{timestamp}, {offset}, {dst}}},")
        print("};")
    print("static const struct zone_entry zone_entries[] = {")
    for name, i, footer, display in zones:
        print(f'    ZONE("{name}", {i}, "{footer}", {int(display)}),')
    print("};")


if __name__ == "__main__":
    main()
