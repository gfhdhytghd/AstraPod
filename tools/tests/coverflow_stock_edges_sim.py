#!/usr/bin/env python3
"""Check Classic's side-cover pixels on the SDL dummy driver.

Usage: coverflow_stock_edges_sim.py ROCKBOXUI RESOURCE_ZIP OUTPUT_DIR
Requires Pillow and ffmpeg. All media is generated by the test.
"""
import runpy
import subprocess
import sys
from pathlib import Path

from PIL import Image


def main():
    binary, assets, out = (Path(arg).resolve() for arg in sys.argv[1:])
    capture = runpy.run_path(Path(__file__).resolve().parents[1] /
                             "capture-readme-gifs.py")
    fixture = out / "simdisk"
    colors = ("blue", "blue", "red", "black", "lime", "blue")
    theme = "native theme: classic\n"
    capture["resources"](assets, fixture, theme)
    for i, color in enumerate(colors, 1):
        album = f"Album {i:02d}"
        path = fixture / "Music" / album
        path.mkdir(parents=True)
        Image.new("RGB", (128, 128), color).save(path / "folder.jpg")
        subprocess.run([
            "ffmpeg", "-nostdin", "-v", "error", "-f", "lavfi", "-i",
            "anullsrc=r=44100:cl=mono", "-t", "1", "-c:a", "flac",
            "-metadata", f"album={album}", "-metadata", "artist=Fixture",
            "-metadata", "title=Silence", str(path / "Track.flac"),
        ], check=True)
    capture["build_library_cache"](binary, fixture, out,
                                   tracks=len(colors), albums=len(colors))
    capture["config"](fixture, theme)

    with capture["Capture"](binary, fixture, out, "covers") as sim:
        tap = capture["tap"]
        sim.run(130)
        sim.run(120, tap("select"))
        for _ in range(2):
            sim.run(85, tap("down"))
        image = Image.frombytes("RGB", capture["SIZE"], sim.latest())
        image.save(out / "coverflow.png")

    def pixel(x, y):
        r, g, b = image.getpixel((x, y))
        return ((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3)

    # At x=235 the upper line touches row 60 with 1/32 white from
    # row 59. The lower line at row 155 uses 11/32 of the half-white
    # reflection in row 156. Rows on either side stay untouched.
    expected = {
        (235, 59): 0xffff, (235, 60): 0x0841, (235, 61): 0x0000,
        (235, 154): 0x0000, (235, 155): 0x3165, (235, 156): 0x840f,
        (223, 100): 0xf800, (224, 100): 0x0000,
        (263, 100): 0x0000,
    }
    for at, value in expected.items():
        actual = pixel(*at)
        assert actual == value, (at, f"expected RGB565 {value:#06x}",
                                  f"got {actual:#06x}")
    # JPEG decoding and ordered dithering can change green by one level.
    assert pixel(264, 100) in (0x07c0, 0x07e0)
    print(f"PASS: {len(expected) + 1} RGB565 checks on settled side covers")


if __name__ == "__main__":
    main()
